#20.compare each order's sales with the previous order's sales and calculate the sales difference. 
WITH ORDERSSALES AS (
SELECT o.ORDER_DATE,o.ORDER_ID,
(O.QUANTITY*P.UNIT_PRICE) AS CURRENT_SALES,
LAG(O.QUANTITY*P.UNIT_PRICE) OVER (ORDER BY o.ORDER_DATE,o.ORDER_ID) AS PREV_SALES
FROM ORDERS o
INNER JOIN PRODUCTS P 
ON o.PRODUCT_ID=P.PRODUCT_ID
)
SELECT ORDER_DATE,ORDER_ID,CURRENT_SALES,PREV_SALES,
(CURRENT_sales-PREV_sales) AS SALES_DIFF
FROM ORDERSSALES;


 
 
 
 
 
 
 
 
 
 
 
 
 